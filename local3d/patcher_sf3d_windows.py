"""Adapt the SF3D checkout for MSVC without touching its upstream repo.

Only edits local3d/stable-fast-3d/{texture_baker,uv_unwrapper}/setup.py.
Creates a core-only requirements list to compile native modules separately.
"""
from __future__ import annotations

import pathlib
import sys


def main() -> int:
    if len(sys.argv) != 2:
        print("Usage: patcher_sf3d_windows.py PATH_TO_LOCAL_SF3D")
        return 2

    source = pathlib.Path(sys.argv[1]).resolve()
    if not (source / "run.py").is_file():
        raise RuntimeError(f"Checkout SF3D non trouve : {source}")

    # Both upstream setup.py files specify GCC-specific -O3/-fopenmp/-march flags.
    # Override only the C++ flags for Microsoft cl.exe; preserve NVCC CUDA flags.
    marker = '    if debug_mode:\n        extra_compile_args["cxx"].append'
    patch = (
        '    # MINO: Windows/MSVC equivalents of GCC-only optimization flags.\n'
        '    if sys.platform == "win32":\n'
        '        extra_compile_args["cxx"] = ["/O2", "/openmp", "/std:c++17"]\n'
    )
    for part in ("texture_baker", "uv_unwrapper"):
        setup_path = source / part / "setup.py"
        text = setup_path.read_text(encoding="utf-8")
        if "import sys\n" not in text:
            text = "import sys\n" + text
        if "MINO: Windows/MSVC equivalents" not in text:
            if text.count(marker) != 1:
                raise RuntimeError(f"Structure inattendue dans {setup_path}; installation arretee.")
            text = text.replace(marker, patch + marker, 1)
            setup_path.write_text(text, encoding="utf-8")
            print(f"Corrige MSVC : {part}/setup.py")
        else:
            print(f"Deja corrige : {part}/setup.py")

    requirements = source / "requirements.txt"
    lines = requirements.read_text(encoding="utf-8").splitlines()
    result = []
    for line in lines:
        value = line.strip()
        if value.startswith("./texture_baker") or value.startswith("./uv_unwrapper"):
            continue
        if value.startswith("rembg[gpu]=="):
            # CPU background removal avoids a second CUDA/ONNX runtime on 8 GB VRAM.
            line = line.replace("rembg[gpu]", "rembg")
        result.append(line)
    output = source / "_mino_requirements_windows.txt"
    output.write_text(
        "# Generated by MINO - install C++ extensions separately on Windows.\n"
        + "\n".join(result)
        + "\n",
        encoding="utf-8",
    )
    print(f"Dependances Python preparees : {output}")
    print("Les fichiers originaux sont modifies uniquement dans cette copie locale.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
